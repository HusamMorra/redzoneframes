<section class="container section static-page">
    <h1>Shipping FAQ</h1>
    <p>Common questions about shipping costs, timelines, and our return policy.</p>

    <h2>How much does shipping cost?</h2>
    <p>Shipping is a flat $5.00 per order, no matter how many frames are in it. Whether you're ordering one frame or ten, the shipping charge stays the same, which is calculated and shown clearly at checkout before you place your order.</p>

    <h2>How long will my order take?</h2>
    <p>Every frame is made to order rather than pulled from a warehouse shelf, so please allow 3-5 business days for production before your order even ships. Once it ships, delivery typically takes another 3-7 business days depending on your location. In total, most orders arrive within 1-2 weeks of being placed.</p>

    <h2>Can I track my order?</h2>
    <p>Yes, once you're logged in, My Account shows the live status of every order you've placed: Pending, Processing, Shipped, or Delivered. There's no separate tracking number system since this is a smaller, made-to-order business, but the status updates as your order moves through production and shipping.</p>

    <h2>Can I return a frame?</h2>
    <p>Since every frame is custom-made specifically for your order, we're not able to accept returns. That said, if your frame arrives damaged in transit, or if there was a production mistake on our end, contact us within 14 days of delivery and we'll remake it and ship the corrected version at no extra charge.</p>

    <h2>What if I made a mistake on my order?</h2>
    <p>Since production begins shortly after an order is placed, reach out through the Contact page as soon as possible if you notice an error. If production hasn't started yet, we can usually make a correction; if it has already gone into production, we'll treat it the same as a production error once it arrives and remake it under our standard policy above.</p>

    <h2>Where do you ship to?</h2>
    <p>Currently we ship within Canada and the United States. If you're outside those areas, reach out through Contact and we can let you know if shipping there is possible.</p>

