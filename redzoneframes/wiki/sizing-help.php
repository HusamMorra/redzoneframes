    <h1>Sizing Help</h1>
    <p>Every frame comes in 3 sizes. Here's a more detailed look at how to decide between them based on where the frame is going and who it's for.</p>

    <h2>8x10 inches - included in the base price</h2>
    <p>This is our smallest size and the one included at no extra cost. It works well on a desk, a bookshelf, or as part of a gallery wall arrangement. If you're buying more than one frame and want to display them together as a set, this size lets you fit more frames into a smaller wall space without overwhelming the room.</p>

    <h2>11x14 inches - our most popular size (+$15.00)</h2>
    <p>This is the size most customers choose when buying just one frame as a standalone piece. It's large enough to genuinely stand out and be the focal point of a wall, without needing a massive empty wall to make sense visually. If you're not sure which size to pick and you're only ordering one frame, this is usually the safest choice.</p>

    <h2>16x20 inches - the statement piece (+$30.00)</h2>
    <p>Our largest option, built for spaces where you want the frame to be impossible to miss, above a couch,, a home theatre, or a sports bar setting. This size works especially well for Retro Legends frames, since the bigger format suits a nostalgic feel.</p>

    <h2>Choosing between sizes</h2>
    <p>A good rule of thumb: measure the wall space you have in mind first. As a general guide, the frame should take up somewhere between a third and half of the visual "block" of space you're filling, so it doesn't look too small and lost, or too large and cramped. If you're framing multiple players as a themed collection, sticking to one consistent size across all of them usually looks the most intentional when displayed together.</p>

